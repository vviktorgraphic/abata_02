Kedves Vendégünk!

A Bata várja Önt! Felkészültünk az érkezésére, amivel kapcsolatban szeretnénk néhány fontos információt megosztani annak érdekében, hogy minél kényelmesebben tudja elfoglalni a szálláshelyet.

Útvonalterv: az alábbi linkre kattintva a Google alapú navigáció egyenesen az épülethez vezeti.
https://maps.app.goo.gl/34kJaMDNo7YNStGv5

Parkolás:
Parkolni az épület közelében az utcában kialakított parkolóhelyeken lehetséges ingyenesen, a szabad kapacitás függvényében. 100 méteren belül szinte bármikor található szabad parkolóhely, a csomagok ki- és bepakolása idejére ideiglenesen az utca egyik oldalára szorosan lehúzódva az épület előtt is meg lehet állni. Az utca nem túl forgalmas, de eléggé szűk, így hosszabb időre semmiképp sem javasoljuk az ott parkolást.

Bejutás a szálláshelyre:
Bár jellemzően személyesen szoktuk átadni a szálláshelyet, egyedi megállapodás és előzetes vendégregisztráció esetén a bejutás és az apartman elfoglalása jelenlétünk nélkül is megoldott.

Az utcafrontról az épület így néz ki (a HTML levélben fényképpel).

A kapu a nap 24 órájában nyitva van. A város biztonságos, ennek ellenére nem javasoljuk, hogy értékeit a kertben tárolja.

Az előkert bal oldala az apartman kizárólagos használatában van, az ott található kerti bútorok az Ön kényelmét szolgálják, ez egyben a szálláshely kijelölt dohányzóhelye is.

A külső homlokzaton 2 db postaládát talál (a HTML levélben fényképpel).

A jobb oldali postaláda jobb oldalán egy kulcsszéfet helyeztünk el. A kulcsszéf kódját az eddig használt kommunikációs csatornán (telefon, SMS, WhatsApp) küldjük el az érkezése előtt nem sokkal.

A szélfogó ajtaját az emeleti lakó az éjszakára zárva tartja. Kérjük ennek az ajtónak zárját mindig hagyja átjutás után a korábbi helyzetében (ha zárva találta kérem zárja vissza, ha nyitva volt, maradjon úgy)!

A szélfogóból egy ajtón keresztül jut a felújított lépcsőházba. Ez az ajtó nem zárható.

A lépcsőház ajtajával szemben találja a szálláshely bejáratát. A többi ajtó a tulajdonosok magánhasználatú helyiségeibe vezet.

A szálláshely felszereléseivel és a környékkel kapcsolatos információkat a nappaliban, a dohányzóasztalon elhelyezett piros borítós mappában találja.

Érezze jól magát nálunk, kérdés, kérés esetén állunk rendelkezésére!

